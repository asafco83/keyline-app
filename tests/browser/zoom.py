import asyncio, sys, json
from playwright.async_api import async_playwright
import os
OUT=os.environ.get('CIN_OUT','/tmp/svgcinema-shots/'); os.makedirs(OUT, exist_ok=True)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await b.new_page(device_scale_factor=2)
        await pg.set_viewport_size({'width':1440,'height':900}); pg.set_default_timeout(5000)
        errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
        await pg.goto((sys.argv[1] if len(sys.argv)>1 else 'http://localhost:5199/'), wait_until='domcontentloaded'); await pg.wait_for_timeout(2500)
        await pg.evaluate("async()=>{ window.st=await import('/src/core/state.ts'); window.hi=await import('/src/core/history.ts'); }")
        ev=lambda js: pg.evaluate(js); R={}; F=[]
        def check(n,c,i=None):
            R[n]=('ok' if c else 'FAIL')+('' if i is None else f' {i}')
            if not c: F.append(n)
        items=lambda: ev("[...document.querySelectorAll('#zoomMenu [data-z]')].map(b=>(b.querySelector('.ck').textContent?'✓ ':'')+[...b.querySelector('.zm-l').childNodes].filter(n=>!(n.classList&&n.classList.contains('ck'))).map(n=>n.textContent).join('').trim()+'|'+b.querySelector('kbd').textContent+(b.disabled?'|off':''))")
        label=lambda: ev("zValT.textContent")
        scale=lambda: ev("st.S.scale")
        await ev("hi.select(null)")
        await pg.click('#zVal'); it=await items()
        check('click the percentage opens the zoom menu', it==['Fit selection|2|off','✓ Fit|1','Zoom 100%|0','Zoom in|Ctrl +','Zoom out|Ctrl −'], it)
        up=await ev("zoomMenu.getBoundingClientRect().bottom<=zVal.getBoundingClientRect().top")
        check('menu opens above the HUD with a slider and a value field', up and await ev("!!document.getElementById('zmRange') && !!document.getElementById('zmNum')"))
        await pg.screenshot(path=(OUT+'zoom')+'-menu.png', clip={'x':880,'y':420,'width':330,'height':360})
        await pg.click('#zoomMenu [data-z="100"]'); s=await scale(); l=await label()
        check('Zoom 100% shows the canvas at actual size', abs(s-1)<1e-6 and l=='100%' and await ev("zoomMenu.hidden"), (s,l))
        await pg.click('#zVal'); it=await items()
        check('the checkmark moves to Zoom 100%', '✓ Zoom 100%|0' in it and 'Fit|1' in it, it)
        await pg.fill('#zmNum','250'); await pg.press('#zmNum','Enter'); s=await scale(); l=await label()
        check('typing 250 + Enter zooms to 250%', abs(s-2.5)<1e-6 and l=='250%' and not await ev("zoomMenu.hidden"), (s,l))
        await ev("document.getElementById('zmRange').focus()")
        await ev("(()=>{const r=document.getElementById('zmRange'); r.value=String(Math.round(+r.value*0.8)); r.dispatchEvent(new Event('input',{bubbles:true}))})()")
        s2=await scale(); n=await ev("zmNum.value")
        check('the slider zooms and the value field follows', s2<2.5 and n==str(round(s2*100)), (s2,n))
        await pg.click('#zoomMenu [data-z="fit"]')
        check('Fit returns to the fitted view', await ev("st.S.zoom===1&&st.S.pan.x===0&&st.S.pan.y===0"))
        sid=await ev("st.doc.layers.find(l=>l.name==='Sun').id"); await ev(f"hi.select('{sid}')")
        await pg.click('#zVal'); it=await items()
        check('Fit selection is available once a layer is selected', 'Fit selection|2' in it, it)
        await pg.click('#zoomMenu [data-z="sel"]')
        c=await ev(f"(()=>{{const r=document.getElementById('e-{sid}').getBoundingClientRect(), w=document.getElementById('wrap').getBoundingClientRect(); return {{dx:(r.left+r.right)/2-(w.left+w.right)/2, dy:(r.top+r.bottom)/2-(w.top+w.bottom)/2, fill:Math.max(r.width/w.width, r.height/w.height)}}}})()")
        check('Fit selection centres and fills the view with the selection', abs(c['dx'])<2 and abs(c['dy'])<2 and c['fill']>0.75, c)
        await ev("document.activeElement.blur()")
        await pg.keyboard.press('1'); a=await ev("st.S.zoom===1&&!st.S.pan.x")
        await pg.keyboard.press('0'); b0=abs(await scale()-1)<1e-6
        await pg.keyboard.press('2'); s2=await scale()
        await pg.keyboard.press('1'); s1=await scale()
        await pg.keyboard.press('Control+Equal'); si=await scale()
        await pg.keyboard.press('Control+Minus'); await pg.keyboard.press('Control+Minus'); so=await scale()
        dpr=await ev("devicePixelRatio")
        check('shortcuts: 1 fit, 0 100%, 2 fit selection, Ctrl +/− zoom (browser zoom untouched)', a and b0 and s2>s1 and abs(si/s1-1.25)<1e-3 and abs(so*1.25/s1-1)<1e-3 and dpr==2, (a,b0,s2,s1,si,so,dpr))
        await pg.keyboard.press('+'); t=await ev("st.S.tool"); await pg.keyboard.press('v')
        check('+ alone still picks the Add node tool', t=='addnode')
        await pg.click('#zVal'); await pg.keyboard.press('Escape')
        check('Escape closes the menu', await ev("zoomMenu.hidden"))
        await pg.screenshot(path=(OUT+'zoom')+'-hud.png', clip={'x':880,'y':640,'width':330,'height':80})
        R['errors']=errs; print(json.dumps(R,indent=1,ensure_ascii=False)); print('FAILS',F)
        await b.close()
asyncio.run(main())
