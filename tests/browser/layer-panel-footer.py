import asyncio, sys, json
from playwright.async_api import async_playwright
import os
OUT=os.environ.get('CIN_OUT','/tmp/svgcinema-shots/'); os.makedirs(OUT, exist_ok=True)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await b.new_page(device_scale_factor=2)
        await pg.set_viewport_size({'width':1440,'height':900}); pg.set_default_timeout(5000)
        errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
        await pg.goto((sys.argv[1] if len(sys.argv)>1 else 'http://localhost:5199/'), wait_until='domcontentloaded'); await pg.wait_for_timeout(2500)
        await pg.evaluate("async()=>{ window.st=await import('/src/core/state.ts'); window.hi=await import('/src/core/history.ts'); }")
        ev=lambda js: pg.evaluate(js)
        R={}; F=[]
        def check(n,c,i=None):
            R[n]=('ok' if c else 'FAIL')+('' if i is None else f' {i}')
            if not c: F.append(n)
        dis=lambda: ev("({anim:lAnim.disabled, ungroup:lUngroup.disabled, group:lGroup.disabled, del:lDel.disabled})")
        menu=lambda: ev("[...document.querySelectorAll('#animMenu button')].map(b=>b.textContent.trim().replace(/\\s+/g,' '))")
        lay=await ev("(()=>{const a=document.getElementById('lp').getBoundingClientRect(),f=document.querySelector('.lp-foot').getBoundingClientRect(),p=document.getElementById('paneLayers').getBoundingClientRect();return {footBelowList:f.top>=a.bottom-1, atBottom:Math.abs(f.bottom-p.bottom)<2, oldBarGone: !document.querySelector('#paneLayers .side-act'), textless:[lGroup,lUngroup,lDel].every(b=>!b.textContent.trim() && b.querySelector('svg'))}})()")
        check('actions sit at the bottom of the layers panel, icon-only', all(lay.values()), lay)
        await ev("hi.select(null)"); d=await dis()
        check('nothing selected: Animate, Ungroup, Delete greyed; Group available', d=={'anim':True,'ungroup':True,'group':False,'del':True}, d)
        rid=await ev("st.doc.layers.find(l=>l.name==='Sun').id"); await ev(f"hi.select('{rid}')"); d=await dis()
        check('shape selected: Animate and Delete on, Ungroup greyed', d=={'anim':False,'ungroup':True,'group':False,'del':False}, d)
        await pg.click('#lAnim'); m=await menu()
        check('Animate menu lists the shape properties with shortcuts', m==['Position⇧ P','Origin⇧ A','Scale⇧ S','Rotate⇧ R','Skew⇧ X','Opacity⇧ O','Fill color','Fill opacity','Stroke color⇧ B','Stroke opacity','Stroke width⇧ W','Trim end (draw on)⇧ D','Dash offset⇧ F','Dash pattern','Size'], m)
        geo=await ev("(()=>{const a=animMenu.getBoundingClientRect(),b=lAnim.getBoundingClientRect();return a.bottom<=b.top})()")
        check('menu opens upwards above the button', geo)
        await pg.screenshot(path=(OUT+'layer-panel-footer')+'-menu.png', clip={'x':60,'y':260,'width':300,'height':640})
        await pg.keyboard.press('Escape'); await ev("hi.setTime(1.25)"); await ev(f"hi.select('{rid}')"); await pg.click('#lAnim')
        await pg.click('#animMenu [data-k="rot"]')
        k=await ev(f"(()=>{{const l=st.doc.layers.find(x=>x.id==='{rid}');return l.t.rot&&l.t.rot.map(q=>q[0])}})()")
        row=await ev(f"!!document.querySelector('.tl-layer [data-lid=\"{rid}\"], .tl-layer[data-lid=\"{rid}\"]') || [...document.querySelectorAll('.tl-lname')].some(e=>e.textContent==='Sun')")
        check('choosing Rotate adds a keyframe at the playhead and the layer joins the timeline', k==[1.25] and row and await ev("animMenu.hidden"), (k,row))
        await ev("document.activeElement.blur()"); await pg.keyboard.press('Shift+O')
        k=await ev(f"(()=>{{const l=st.doc.layers.find(x=>x.id==='{rid}');return l.t.op&&l.t.op.map(q=>q[0])}})()")
        check('Shift+O animates opacity', k==[1.25], k)
        tool=await ev("st.S.tool"); await pg.keyboard.press('Shift+C'); t2=await ev("st.S.tool"); await pg.keyboard.press('v')
        check('Shift+C still selects the Convert Point tool', t2=='convert', (tool,t2))
        gid=await ev("st.doc.layers.find(l=>l.type==='group').id"); await ev(f"hi.select('{gid}')"); d=await dis()
        await pg.click('#lAnim'); m=await menu(); await pg.keyboard.press('Escape')
        check('group selected: Ungroup on; menu shows only transform and opacity', d['ungroup']==False and m==['Position⇧ P','Origin⇧ A','Scale⇧ S','Rotate⇧ R','Skew⇧ X','Opacity⇧ O'], (d,m))
        check('Escape closes the menu', await ev("animMenu.hidden"))
        pid=await ev("st.doc.layers.find(l=>l.type==='path').id"); await ev(f"hi.select('{pid}')"); await pg.click('#lAnim'); m=await menu(); await pg.click('#lAnim')
        check('path selected: menu includes Morph path', 'Morph path⇧ M' in m, m[-1])
        await ev(f"hi.select('{rid}')"); await ev(f"(()=>{{st.doc.layers.find(x=>x.id==='{rid}').lock=true; hi.commit({{insp:true}})}})()"); d=await dis()
        check('locked layer: Animate greyed', d['anim'], d)
        await ev(f"(()=>{{st.doc.layers.find(x=>x.id==='{rid}').lock=false; hi.select(null)}})()")
        await pg.screenshot(path=(OUT+'layer-panel-footer')+'-none.png', clip={'x':60,'y':560,'width':300,'height':340})
        R['errors']=errs; print(json.dumps(R,indent=1,ensure_ascii=False)); print('FAILS',F)
        await b.close()
asyncio.run(main())
